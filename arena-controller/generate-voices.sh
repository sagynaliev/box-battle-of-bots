#!/bin/bash
set -euo pipefail

base="$(cd "$(dirname "$0")" && pwd)"
voice="${1:-Samantha}"
target="$base/ArenaController/VoiceAssets.h"
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT

render() {
  say -v "$voice" -o "$scratch/$1.aiff" "$2"
  ffmpeg -nostdin -loglevel error -y -i "$scratch/$1.aiff" \
    -ac 1 -ar 16000 -c:a pcm_u8 -f u8 "$scratch/$1.raw"
}

render voiceFight 'Three, two, one, FIGHT!'
render voiceStop 'Stop the battle!'
render voiceRound 'Round finished!'
render voiceBlue 'Introducing the Blue Team!'
render voiceRed 'Introducing the Red Team!'
render voiceFinal 'Ladies and gentlemen, we have a winner!'
render voiceBlueWins 'The Blue Team wins!'
render voiceRedWins 'The Red Team wins!'

python3 - "$scratch" "$target" <<'PY'
import sys
from pathlib import Path

source, target = map(Path, sys.argv[1:])
lines = ["#pragma once", "#include <stdint.h>", "",
         "// Generated by generate-voices.sh. Mono unsigned PCM at 16000 Hz.", ""]
for path in sorted(source.glob("*.raw")):
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"Empty recording: {path.name}")
    lines.append(f"static const uint8_t {path.stem}[] = {{")
    for start in range(0, len(data), 20):
        lines.append("  " + ", ".join(map(str, data[start:start + 20])) + ",")
    lines.extend(["};", ""])
target.write_text("\n".join(lines))
PY
